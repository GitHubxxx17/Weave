import { z } from 'zod';
import { messageSchema } from './messages.js';
import { toolDefinitionSchema } from './tools.js';

const nonNegativeFiniteNumberSchema = z.number().finite().nonnegative();
const tokenCountSchema = z.number().int().nonnegative().safe();

/** Normalized reasons why a model stream stopped producing output. */
export type FinishReason = 'stop' | 'tool-call' | 'length' | 'content-filter' | 'unknown';

/**
 * Provider-independent token accounting reported for one model request.
 *
 * Providers may omit fields they do not report, so consumers must not assume
 * that `totalTokens` or cache counters are always present.
 */
export interface TokenUsage {
  /** Tokens consumed by the input prompt. */
  readonly inputTokens?: number;
  /** Tokens generated by the model. */
  readonly outputTokens?: number;
  /** Provider-reported input plus output total. */
  readonly totalTokens?: number;
  /** Input tokens served from a provider cache. */
  readonly cacheReadTokens?: number;
  /** Input tokens written to a provider cache. */
  readonly cacheWriteTokens?: number;
  /** Tokens attributed to hidden or explicit reasoning. */
  readonly reasoningTokens?: number;
}

/** Validates provider-independent token usage data. */
export const tokenUsageSchema = z
  .object({
    inputTokens: tokenCountSchema.optional(),
    outputTokens: tokenCountSchema.optional(),
    totalTokens: tokenCountSchema.optional(),
    cacheReadTokens: tokenCountSchema.optional(),
    cacheWriteTokens: tokenCountSchema.optional(),
    reasoningTokens: tokenCountSchema.optional(),
  })
  .passthrough();

/**
 * Provider-independent request sent to an LLM client.
 *
 * Provider adapters translate this shape into their wire protocol. The
 * provider name is routing metadata and is not itself sent blindly to every
 * provider endpoint.
 */
export interface LlmRequest {
  /** Provider registry key used to select an adapter. */
  readonly provider: string;
  /** Model identifier understood by the selected provider. */
  readonly model: string;
  /** Ordered conversation history. */
  readonly messages: readonly z.infer<typeof messageSchema>[];
  /** Tools made available to the model for this request. */
  readonly tools?: readonly z.infer<typeof toolDefinitionSchema>[];
  /** Sampling temperature, when supported by the provider. */
  readonly temperature?: number;
  /** Maximum generated token count, when supported by the provider. */
  readonly maxTokens?: number;
  /** Provider-specific reasoning effort hint. */
  readonly reasoningEffort?: string;
}

/** Validates an LLM request before it reaches a provider adapter. */
export const llmRequestSchema = z
  .object({
    provider: z.string(),
    model: z.string(),
    messages: z.array(messageSchema).readonly(),
    tools: z.array(toolDefinitionSchema).readonly().optional(),
    temperature: nonNegativeFiniteNumberSchema.optional(),
    maxTokens: nonNegativeFiniteNumberSchema.optional(),
    reasoningEffort: z.string().optional(),
  })
  .passthrough();

/**
 * Incremental events emitted by an LLM stream.
 *
 * These are transient transport events, not durable Session events. The Agent
 * Loop decides how and when to persist them as durable facts.
 */
export type StreamEvent =
  | { readonly type: 'text-delta'; readonly text: string }
  | { readonly type: 'reasoning-delta'; readonly text: string }
  | { readonly type: 'tool-call-start'; readonly id: string; readonly name: string }
  | { readonly type: 'tool-call-delta'; readonly id: string; readonly argumentsDelta: string }
  | {
      readonly type: 'finish';
      readonly reason: FinishReason;
      readonly usage?: TokenUsage;
    };

const textDeltaSchema = z
  .object({
    type: z.literal('text-delta'),
    text: z.string(),
  })
  .passthrough();

const reasoningDeltaSchema = z
  .object({
    type: z.literal('reasoning-delta'),
    text: z.string(),
  })
  .passthrough();

const toolCallStartSchema = z
  .object({
    type: z.literal('tool-call-start'),
    id: z.string(),
    name: z.string(),
  })
  .passthrough();

const toolCallDeltaSchema = z
  .object({
    type: z.literal('tool-call-delta'),
    id: z.string(),
    argumentsDelta: z.string(),
  })
  .passthrough();

const finishSchema = z
  .object({
    type: z.literal('finish'),
    reason: z.enum(['stop', 'tool-call', 'length', 'content-filter', 'unknown']),
    usage: tokenUsageSchema.optional(),
  })
  .passthrough();

/** Validates incremental events emitted by an LLM client. */
export const streamEventSchema = z.discriminatedUnion('type', [
  textDeltaSchema,
  reasoningDeltaSchema,
  toolCallStartSchema,
  toolCallDeltaSchema,
  finishSchema,
]);
